#!/usr/bin/env python3
"""Run the real Badge Runtime graph and unchanged maintained Home on a host.

Uses the exact staged target JSON, host-built production provider/Home modules,
real Runtime::prepare/run, ProviderGraphV2, CpuPort and NativeRealtime. Lowest
hardware/SDK and boot-lifetime callbacks, file-source fixtures, and host ELF
admission/instruction mapping are models, not public capability substitutes.
A separately labeled app probe qualifies retry and retained-cleanup paths.
This is not target ELF-loader, firmware-boot, or physical-hardware evidence.
Leak detection defaults on. Ptrace hosts must explicitly set
ASAN_OPTIONS=detect_leaks=0; the receipt records that exclusion.
"""
import argparse
import ast
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess
import sys
import tempfile
from cst9217_sdk import stage_sdk

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / "boards/waveshare-esp32-s3-touch-amoled-1.75c"
MODES = ("home", "home-supply-failure", "home-display-failure", "home-touch-failure",
         "probe-start-retry", "probe-release-retry", "probe-start-retained",
         "probe-i2c-retained", "home-shutdown-retained")
RETAINED = {"probe-start-retained", "probe-i2c-retained", "home-shutdown-retained"}


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name, default in (("watch", "badge-display-watch"), ("runtime", "badge-display-runtime"),
                          ("system", "badge-home-system"), ("utilities", "badge-home-utilities"),
                          ("controllers", "badge-home-controllers")):
        parser.add_argument("--" + name, type=Path, default=ROOT.parent / default)
    parser.add_argument("--store", type=Path, required=True, help="store generated by build_badge_home.py")
    parser.add_argument("--sanitize", action="store_true")
    parser.add_argument("--output", type=Path, help="write machine-readable evidence JSON")
    args = parser.parse_args()
    # A failed preflight/build/test must never leave a stale PASS at this path.
    if args.output:
        args.output.unlink(missing_ok=True)
    if platform.system() != "Linux":
        parser.error("This host-loader observer currently requires Linux/GNU ld --wrap")
    roots = {name: getattr(args, name).resolve() for name in ("watch", "runtime", "system", "utilities", "controllers")}
    lock = json.loads((BOARD / "home/sources.lock.json").read_text())
    pins = {name: lock[name]["commit"] for name in roots}
    commands = []
    def run(command, **kwargs):
        command = list(map(str, command)); commands.append(command)
        return subprocess.run(command, check=True, **kwargs)
    watch, runtime, system, utilities, controllers = (roots[n] for n in ("watch", "runtime", "system", "utilities", "controllers"))
    inputs = load_module("badge_runtime_build_inputs", watch / "scripts/build_inputs.py")
    dependency_paths = {
        "watch": ["apps", "include", "sdk", "scripts", "dependencies.lock.json"],
        "runtime": ["src", "sdk", "lib/ArduinoJson", "lib/hal", "lib/elf_loader", "test/RuntimeFileFixture.h",
                    "test/drivers/stubs", "test/realtime_shim", "test/retained_wake_shim"],
        "system": ["lib/PortableApps"],
        "utilities": ["Apps/alarm_writer.h", "lib/Alarm/include", "lib/Contexts/include"],
        "controllers": ["drivers/twatch_i2c", "include"],
    }
    # Verify actual worktree bytes against each pinned Git blob, including
    # untracked additions, then bind and recheck those same bytes after testing.
    verified_dependencies = {name: inputs.verify_dependency(roots[name], pins[name], paths)
                             for name, paths in dependency_paths.items()}
    tree = ast.parse((watch / "scripts/build.py").read_text())
    expression = next(n.value for n in tree.body if isinstance(n, ast.Assign)
                      and any(isinstance(t, ast.Name) and t.id == "FLAGS" for t in n.targets))
    flags = eval(compile(ast.Expression(expression), "production FLAGS", "eval"), {"__builtins__": {}})
    assert all(isinstance(flag, str) for flag in flags)
    source_store = args.store.resolve()
    # Use generated target metadata verbatim, never a handwritten test graph.
    json_files = sorted(source_store.rglob("*.json"))
    assert {p.relative_to(source_store).as_posix() for p in json_files} == {
        "board.json", "boot.json", "default.json", "i2c/manifest.json", "display/manifest.json",
        "touch/manifest.json", "supply/manifest.json"}
    for name in ("board.json", "boot.json"):
        assert (source_store / name).read_bytes() == (BOARD / "home" / name).read_bytes(), name
    builder = load_module("badge_home_store_builder", ROOT / "scripts/build_badge_home.py")
    original = json.loads((watch / "apps/clock/default.json").read_text())
    boot = json.loads((source_store / "boot.json").read_text())
    assert original["version"] == "0.19.4"
    assert json.loads((source_store / "default.json").read_text()) == builder.home_manifest(original, boot["app_capabilities"][0])
    assert boot["provider_activation"] == "demand-retained"
    receipt = source_store.parent / "shared-home/build.json"
    assert receipt.is_file(), "The staged target store needs its shared Home build receipt"
    assert json.loads(receipt.read_text())["artifacts"]["default"]["defines"] == flags
    scoped_i2c = ROOT / "components/i2c-scoped/driver.c"
    providers = {
        "i2c": scoped_i2c,
        "display": ROOT / "components/co5300/facade/driver.c",
        "touch": ROOT / "Drivers/cst9217_touch/driver.c",
        "supply": BOARD / "supply/driver.c",
    }
    for name, source in providers.items():
        assert (source_store / name / "manifest.json").read_bytes() == source.with_name("manifest.json").read_bytes(), f"Stale staged {name} manifest"
    home_sources = [watch / "apps/clock" / n for n in
                    ("crown.c", "viewport.c", "capability_clients.c", "quick_radios.c", "nova/nova.c", "points_projection.c", "effects/divdi3.c")]
    home_sources += [system / "lib/PortableApps/src" / n for n in ("quick_actions.c", "quick_render.c", "quick_session.c")]
    runtime_sources = [runtime / path for path in (
        "src/bootstrap/Json.cpp", "src/bootstrap/Board.cpp", "src/bootstrap/Runtime.cpp",
        "src/runtime/drivers/ProviderGraphV2.cpp", "src/runtime/drivers/ProviderModuleV2.cpp",
        "src/ports/esp32s3/CpuPort.cpp", "src/runtime/streams/AppStreamSessions.cpp",
        "src/runtime/streams/ProviderQueueHost.cpp")]
    production = set([*json_files, receipt, *providers.values(),
                      *[source.with_name("manifest.json") for source in providers.values()],
                      BOARD / "home/board.json", BOARD / "home/boot.json", *home_sources, *runtime_sources,
                      watch / "scripts/build.py", watch / "apps/clock/effects/boot.cpp",
                      BOARD / "display-profile.h", BOARD / "home/sources.lock.json", ROOT / "scripts/build_badge_home.py",
                      runtime / "src/ports/esp32s3/NativeRealtime.cpp", ROOT / "tests/badge_runtime_execution.cpp",
                      ROOT / "tests/badge_runtime_app_probe.c", Path(__file__).resolve(), ROOT / "scripts/cst9217_sdk.py"])
    for directory in (ROOT / "components/co5300", ROOT / "components/i2c-scoped", ROOT / "sdk/driver"):
        production.update(p for p in directory.rglob("*") if p.is_file() and p.suffix in {".c", ".h", ".json"})
    def digests():
        return {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(production)}
    before = digests()
    cc = shlex.split(os.environ.get("CC", "cc")); cxx = shlex.split(os.environ.get("CXX", "c++"))
    common = ["-O1", "-g", "-Wall", "-Wextra", "-Werror"]
    sanitizer = ["-fsanitize=address,undefined", "-fno-sanitize-recover=all", "-fno-omit-frame-pointer"] if args.sanitize else []
    results = {}
    with tempfile.TemporaryDirectory(prefix="badge-runtime-execution-") as temp:
        out = Path(temp); store = out / "store"; store.mkdir()
        for path in json_files:
            destination = store / path.relative_to(source_store); destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, destination)
        merged = load_module("badge_runtime_merged_sdk", watch / "scripts/merged_sdk.py")
        sdk = merged.headers(out, system, utilities, watch)
        provider_sdk = out / "provider-sdk"; provider_sdk.mkdir()
        for directory in (watch / "sdk/driver", watch / "sdk/app"):
            for header in directory.glob("*.h"):
                shutil.copyfile(header, provider_sdk / header.name)
        stage_sdk(ROOT, runtime, provider_sdk)
        includes = ["-I" + str(p) for p in (sdk, watch / "include", watch, system / "lib/PortableApps/src")]
        objects = []
        for number, source in enumerate(home_sources):
            obj = out / f"home-{number}.o"
            run([*cc, "-std=c11", *common, *sanitizer, "-fPIC", "-fvisibility=hidden", *flags, *includes, "-c", source, "-o", obj])
            objects.append(obj)
        effect = out / "boot.o"
        run([*cxx, "-std=c++11", *common, *sanitizer, "-fPIC", "-fvisibility=hidden", "-fno-exceptions", "-fno-rtti",
             "-fno-threadsafe-statics", *includes, "-c", watch / "apps/clock/effects/boot.cpp", "-o", effect])
        home_image = out / "home.elf"
        run([*cxx, *sanitizer, *flags, "-shared", *objects, effect, "-o", home_image])
        provider_includes = ["-I" + str(p) for p in (provider_sdk, ROOT / "components/co5300/include", watch / "include", controllers / "include")]
        for name, source in providers.items():
            extra = ["-include", BOARD / "display-profile.h"] if name == "display" else []
            run([*cc, "-std=c11", *common, *sanitizer, "-fPIC", "-shared", "-fvisibility=hidden",
                 *provider_includes, *extra, source, "-o", store / name / "driver.elf"])
        probe = out / "probe.elf"
        run([*cc, "-std=c11", *common, *sanitizer, "-fPIC", "-shared", "-fvisibility=hidden", "-I" + str(runtime / "sdk/app"), *provider_includes,
             ROOT / "tests/badge_runtime_app_probe.c", "-o", probe])
        runtime_includes = ["-I" + str(runtime / p) for p in
                            ("src", "sdk/app", "sdk/driver", "sdk/hardware", "lib/ArduinoJson/src", "test",
                             "test/drivers/stubs", "test/realtime_shim", "test/retained_wake_shim")]
        binary = out / "runtime-test"
        # Match the Runtime admission suite's unoptimized sanitizer lane;
        # keep -Werror without GCC -O1's pinned ArduinoJson end-iterator warning.
        runtime_optimization = ["-O0"] if args.sanitize else []
        run([*cxx, "-std=c++17", *common, *runtime_optimization, *sanitizer, "-Wno-missing-field-initializers", "-Wno-misleading-indentation",
             "-rdynamic", "-DRISC_STAGE_LOGS=1", "-DRISC_APP_REQUIREMENT_ROWS=24", *runtime_includes,
             *runtime_sources, ROOT / "tests/badge_runtime_execution.cpp", "-Wl,--wrap=dlopen", "-Wl,--wrap=dlclose",
             "-ldl", *(["-no-pie"] if args.sanitize else []), "-o", binary])
        host_sha256 = {name: hashlib.sha256(path.read_bytes()).hexdigest() for name, path in
                       [("home", home_image), ("probe", probe), *[(n, store / n / "driver.elf") for n in providers]]}
        for mode in MODES:
            shutil.copyfile(probe if mode.startswith("probe-") else home_image, store / "default.elf")
            env = os.environ.copy()
            if args.sanitize:
                env["ASAN_OPTIONS"] = env.get("ASAN_OPTIONS", "detect_leaks=1") + ":halt_on_error=1"
                env["UBSAN_OPTIONS"] = env.get("UBSAN_OPTIONS", "") + ":halt_on_error=1:print_stacktrace=1"
            result = subprocess.run([str(binary), str(store), mode], text=True, capture_output=True, env=env, timeout=120)
            print(result.stdout, end=""); print(result.stderr, end="", file=sys.stderr); result.check_returncode()
            assert f"BADGE_RUNTIME mode={mode} result=PASS" in result.stdout
            results[mode] = {"application": "lifecycle probe" if mode.startswith("probe-") else "unchanged maintained Home 0.19.4",
                             "retained": mode in RETAINED, "stdout": result.stdout,
                             "leak_check": bool(args.sanitize and mode not in RETAINED and "detect_leaks=0" not in env.get("ASAN_OPTIONS", ""))}
    assert digests() == before, "Inputs changed during Runtime execution qualification"
    for name, paths in dependency_paths.items():
        assert inputs.verify_dependency(roots[name], pins[name], paths) == verified_dependencies[name], name
    evidence = {"schema": 1, "result": "PASS", "production_pins": pins, "production_input_sha256": before,
                "verified_dependencies": verified_dependencies, "dependency_bytes_rechecked": True,
                "staged_store": str(source_store), "staged_metadata_sha256": {
                    p.relative_to(source_store).as_posix(): before[str(p)] for p in json_files},
                "output_cleared_before_preflight": True,
                "home_production_flags": flags, "home_source_modified": False, "host_module_sha256": host_sha256,
                "native_realtime": "actual NativeRealtime; POWERON => UNSET; no seeds or wall-clock reads",
                "real_runtime_prepare_and_run": True, "real_provider_graph_and_cpu_port": True,
                "target_metadata_unchanged": True, "home_cases": 5, "separate_lifecycle_probe_cases": 4,
                "sanitizers": "address,undefined" if args.sanitize else None,
                "asan_options": env.get("ASAN_OPTIONS") if args.sanitize else None,
                "retained_cases": "Intentional process-exit retention; no destructor, cleanup retry, or leak-check claim",
                "target_elf_loader_tested": False, "firmware_boot_tested": False,
                "native_boot_confirmation_tested": False, "physical_hardware_tested": False,
                "modeled_boundaries": ["lowest GPIO", "I2C register transfers", "display transport",
                    "SDK reset/timer/wall syscalls", "test boot owner callback", "health lifetime bound",
                    "boot confirmation hook (real Runtime routing, no native bank confirmation)", "diagnostic sink",
                    "host Posix RuntimeFileSources fixture with test owner/safety checks",
                    "pinned esp_dlfcn.h host ELF magic-only validation and always-true managed-app admission",
                    "independent host instruction mapping, not target Xtensa relocation"],
                "cases": results, "commands": commands}
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(evidence, indent=2) + "\n")
    print("Badge Runtime execution: 9 scenarios " + ("ASan/UBSan" if args.sanitize else "normal") + " PASS")


if __name__ == "__main__":
    main()
